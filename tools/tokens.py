"""Generate the pure Java Folio constants from design/tokens.json."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "app/src/main/java/dev/inkhome/folio/core/Tokens.java"


def render(groups):
    lines = ["// Generated by tools/tokens.py from design/tokens.json.",
             "package dev.inkhome.folio.core;", "", "public final class Tokens {",
             "    private Tokens() {}"]
    for group, values in groups.items():
        name = group[0].upper() + group[1:]
        lines.extend(["", f"    public static final class {name} {{",
                      f"        private {name}() {{}}"])
        for key, value in values.items():
            constant = re.sub(r"(?=[A-Z])", "_", key).upper()
            if type(value) is int:
                kind, literal = "int", str(value)
            elif type(value) is float:
                kind, literal = "float", f"{value}f"
            elif isinstance(value, str) and re.fullmatch(r"#[\da-fA-F]{6}", value):
                kind, literal = "int", "0xFF" + value[1:]
            else:
                raise ValueError(f"Invalid token {group}.{key}: {value!r}")
            lines.append(f"        public static final {kind} {constant} = {literal};")
        lines.append("    }")
    return "\n".join([*lines, "}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit nonzero if regeneration is needed")
    args = parser.parse_args()
    result = render(json.loads((ROOT / "design/tokens.json").read_text(encoding="utf-8")))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != result:
            parser.exit(1, "Regenerate Tokens.java with python tools/tokens.py\n")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_bytes(result.encode())


if __name__ == "__main__":
    main()
