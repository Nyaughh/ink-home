package dev.inkhome.folio.core;

import static dev.inkhome.folio.core.Tokens.Type.*;

public enum TypeScale {
    DISPLAY(DISPLAY_SIZE, DISPLAY_LINE, DISPLAY_WEIGHT_EINK, DISPLAY_WEIGHT_EMISSIVE),
    FIGURE(FIGURE_SIZE, FIGURE_LINE, FIGURE_WEIGHT_EINK, FIGURE_WEIGHT_EMISSIVE),
    TITLE_LG(TITLE_LG_SIZE, TITLE_LG_LINE, TITLE_LG_WEIGHT_EINK, TITLE_LG_WEIGHT_EMISSIVE),
    TITLE(TITLE_SIZE, TITLE_LINE, TITLE_WEIGHT_EINK, TITLE_WEIGHT_EMISSIVE),
    TITLE_EXPANDED(TITLE_EXPANDED_SIZE, TITLE_EXPANDED_LINE, TITLE_EXPANDED_WEIGHT_EINK, TITLE_EXPANDED_WEIGHT_EMISSIVE),
    TITLE_MD(TITLE_MD_SIZE, TITLE_MD_LINE, TITLE_MD_WEIGHT_EINK, TITLE_MD_WEIGHT_EMISSIVE),
    TITLE_SM(TITLE_SM_SIZE, TITLE_SM_LINE, TITLE_SM_WEIGHT_EINK, TITLE_SM_WEIGHT_EMISSIVE),
    BYLINE(BYLINE_SIZE, BYLINE_LINE, BYLINE_WEIGHT_EINK, BYLINE_WEIGHT_EMISSIVE),
    BODY_LG(BODY_LG_SIZE, BODY_LG_LINE, BODY_LG_WEIGHT_EINK, BODY_LG_WEIGHT_EMISSIVE),
    BODY(BODY_SIZE, BODY_LINE, BODY_WEIGHT_EINK, BODY_WEIGHT_EMISSIVE),
    META(META_SIZE, META_LINE, META_WEIGHT_EINK, META_WEIGHT_EMISSIVE),
    LABEL(LABEL_SIZE, LABEL_LINE, LABEL_WEIGHT_EINK, LABEL_WEIGHT_EMISSIVE),
    APP_NAME(BODY_LG_SIZE, BODY_LG_LINE, APP_NAME_WEIGHT_EINK, BODY_LG_WEIGHT_EMISSIVE),
    CHART(MIN_CHART_SIZE, META_LINE, META_WEIGHT_EINK, META_WEIGHT_EMISSIVE),
    READING(READING_SIZE, READING_SIZE * READING_LINE_MULTIPLIER, READING_WEIGHT, READING_WEIGHT);

    public final float size, line;
    private final int einkWeight, emissiveWeight;

    TypeScale(float size, float line, int einkWeight, int emissiveWeight) {
        this.size = size;
        this.line = line;
        this.einkWeight = einkWeight;
        this.emissiveWeight = emissiveWeight;
    }

    public int weight(DisplayClass display) { return display.isEink() ? einkWeight : emissiveWeight; }

    public TypeScale forWindow(WindowClass window) {
        return this == TITLE && window == WindowClass.EXPANDED ? TITLE_EXPANDED : this;
    }
}
